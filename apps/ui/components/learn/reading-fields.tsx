"use client";

import { useEffect, useRef } from "react";

export type PartOfSpeech = "verb" | "noun" | "adjective" | "phrase";

export const POS_LABEL: Record<PartOfSpeech, string> = {
  verb: "Động từ",
  noun: "Danh từ",
  adjective: "Tính từ",
  phrase: "Cụm từ",
};

const inputClass =
  "block w-full rounded-lg border border-[var(--border)] bg-[var(--background)] px-3 py-2 text-sm text-[var(--foreground)] placeholder:text-[var(--muted-foreground)] focus:border-[var(--primary-focus)] focus:outline-none focus:ring-1 focus:ring-[var(--primary-focus)]";

/**
 * Hiragana + part-of-speech inputs for a card.
 *
 * When the front (term) changes, the reading is generated by the API
 * (`POST /api/flashcards/reading`): kanji words get their hiragana, while
 * hiragana-only and katakana words get an EMPTY reading. A suggested part of
 * speech (verb / noun / adjective) is filled in too. Anything the user types
 * or selects by hand is never overwritten afterwards.
 *
 * Mount it with a `key` that changes when the parent resets the form so the
 * "touched" flags reset as well.
 */
export function ReadingFields({
  front,
  reading,
  partOfSpeech,
  onReading,
  onPartOfSpeech,
  autoOnMount = true,
}: {
  front: string;
  reading: string;
  partOfSpeech: PartOfSpeech | "";
  onReading: (v: string) => void;
  onPartOfSpeech: (v: PartOfSpeech | "") => void;
  /** `false` when editing: keep the saved values until the front changes. */
  autoOnMount?: boolean;
}) {
  const readingTouched = useRef(false);
  const posTouched = useRef(false);
  const firstRun = useRef(true);
  // Latest callbacks without re-triggering the debounce effect.
  const cb = useRef({ onReading, onPartOfSpeech });
  useEffect(() => {
    cb.current = { onReading, onPartOfSpeech };
  });

  useEffect(() => {
    if (firstRun.current) {
      firstRun.current = false;
      if (!autoOnMount) return;
    }
    const text = front.trim();
    if (text === "") {
      if (!readingTouched.current) cb.current.onReading("");
      return;
    }
    let cancelled = false;
    const timer = window.setTimeout(async () => {
      const res = await fetch("/api/flashcards/reading", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ text }),
      }).catch(() => null);
      if (cancelled || !res?.ok) return;
      const data = (await res.json().catch(() => null)) as {
        reading?: string;
        partOfSpeech?: PartOfSpeech | null;
      } | null;
      if (cancelled || !data) return;
      if (!readingTouched.current) cb.current.onReading(data.reading ?? "");
      if (!posTouched.current && data.partOfSpeech) {
        cb.current.onPartOfSpeech(data.partOfSpeech);
      }
    }, 450);
    return () => {
      cancelled = true;
      window.clearTimeout(timer);
    };
  }, [front, autoOnMount]);

  return (
    <>
      <label className="block text-sm">
        <span className="text-[var(--muted-foreground)]">
          Hiragana (tự tạo từ kanji; trống nếu từ không có kanji)
        </span>
        <input
          value={reading}
          lang="ja"
          onChange={(e) => {
            readingTouched.current = true;
            onReading(e.target.value);
          }}
          className={`mt-1 ${inputClass}`}
          placeholder="ねこ"
        />
      </label>
      <label className="block text-sm">
        <span className="text-[var(--muted-foreground)]">Từ loại</span>
        <select
          value={partOfSpeech}
          onChange={(e) => {
            posTouched.current = true;
            onPartOfSpeech(e.target.value as PartOfSpeech | "");
          }}
          className={`mt-1 ${inputClass}`}
        >
          <option value="">— Không phân loại —</option>
          <option value="verb">{POS_LABEL.verb}</option>
          <option value="noun">{POS_LABEL.noun}</option>
          <option value="adjective">{POS_LABEL.adjective}</option>
          <option value="phrase">{POS_LABEL.phrase}</option>
        </select>
      </label>
    </>
  );
}

/** Small coloured chip for a part of speech. */
export function PosChip({ pos }: { pos?: string }) {
  if (pos !== "verb" && pos !== "noun" && pos !== "adjective" && pos !== "phrase") return null;
  const tone = {
    verb: "bg-[#dbeafe] text-[#1d4ed8] dark:bg-[#172554] dark:text-[#93c5fd]",
    noun: "bg-[#dcfce7] text-[#15803d] dark:bg-[#052e16] dark:text-[#86efac]",
    adjective: "bg-[#fef3c7] text-[#b45309] dark:bg-[#422006] dark:text-[#fcd34d]",
    phrase: "bg-[#f3e8ff] text-[#7e22ce] dark:bg-[#3b0764] dark:text-[#d8b4fe]",
  }[pos];
  return (
    <span className={`inline-block rounded-full px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wide ${tone}`}>
      {POS_LABEL[pos]}
    </span>
  );
}
