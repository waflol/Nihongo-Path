import { Prop, Schema, SchemaFactory } from "@nestjs/mongoose";
import { HydratedDocument, Types } from "mongoose";
import { MONDAI_TYPES, type MondaiType } from "../../exams/mondai.js";

/**
 * The shape of a saved multiple-choice question. The vocabulary section of the
 * JLPT / Nattest practice is organised as six 問題 (mondai):
 *   1 Cách đọc kanji → `reading-pick`     2 Cách đọc Hiragana → `kanji-pick`
 *   3 Cấu tạo từ     → `formation-pick`   4 Đồng nghĩa        → `synonym-pick`
 *   5 Biểu hiện từ   → `context-pick`     6 Cách dùng từ      → `sentence-pick`
 * (`meaning-pick` is the plain flashcard-style quiz, outside those six.)
 *
 * The exam-bank types (NP-406) add three more:
 *   `grammar-form`  a single sentence's blank   `star-order`  a ★-marked cloze
 *   `passage-question` a question that attaches to a shared reading passage
 * (`exam_stimuli`). These are authored into the bank, never generated from a
 * card, so the learner exercise flow ignores them.
 */
export const EXERCISE_KINDS = [
  "kanji-pick", // reading shown → pick the kanji spelling
  "reading-pick", // kanji shown → pick the hiragana reading
  "meaning-pick", // word shown → pick the meaning
  "synonym-pick", // word shown → pick the synonym
  "sentence-pick", // word shown → pick the sentence that uses it correctly
  "formation-pick", // word with one kanji hidden → pick the missing kanji
  "context-pick", // sentence with a blank → pick the word that fits
  // Exam-bank (NP-406) — authored into the bank, not generated from cards.
  "grammar-form", // a single sentence's blank (grammar)
  "star-order", // a sentence with four ＿＿ blanks, one ★
  "passage-question", // a question bound to a shared reading passage
] as const;
export type ExerciseKind = (typeof EXERCISE_KINDS)[number];

/** JLPT paper parts a bank question can belong to (NP-406). */
export const QUESTION_SECTIONS = ["vocab", "grammar", "reading", "listening"] as const;
export type QuestionSection = (typeof QUESTION_SECTIONS)[number];

/** Where a question's content rights live (NP-406, Q-12). */
export const QUESTION_RIGHTS = ["own", "licensed", "reference"] as const;
export type QuestionRights = (typeof QUESTION_RIGHTS)[number];

/**
 * One question in the multiple-choice question bank: generated by the
 * exercises area, authored by the admin, or both. Every question the
 * learner sees is kept (once) and reused — the JLPT / Nattest practice and
 * the exam engine (P4) pull their items from this bank.
 *
 * `deck` / `card` are optional: learner-generated questions carry the deck
 * and card that produced them; admin-authored standalone questions
 * (P4-EXAM-01) carry neither.
 *
 * `dedupeKey` fingerprints (deck, card, kind, answer, sorted options): showing
 * the same question again never creates a second row, while a new set of
 * distractors for the same card is kept as a different question.
 * `verified` is true when the answer was checked — against the card itself
 * for learner-generated rows, by the author for standalone rows.
 */
@Schema({ _id: true, timestamps: true, collection: "exercise_questions" })
export class ExerciseQuestion {
  @Prop({ type: Types.ObjectId, ref: "FlashcardDeck" })
  deck?: Types.ObjectId | null;

  @Prop({ type: Types.ObjectId, ref: "Flashcard" })
  card?: Types.ObjectId | null;

  @Prop({ type: String, enum: EXERCISE_KINDS, required: true })
  kind: ExerciseKind;

  /** The question stem (a reading, a word, …). */
  @Prop({ type: String, required: true })
  prompt: string;

  /** A hint under the stem (usually the Vietnamese meaning). */
  @Prop({ type: String, default: "" })
  sub?: string;

  /** Exactly four distinct options, in the order they were shown. */
  @Prop({ type: [String], required: true })
  options: string[];

  @Prop({ type: String, required: true })
  answer: string;

  /** Shown after answering (e.g. a sentence's translation). */
  @Prop({ type: String, default: "" })
  explain?: string;

  /** Where the distractors came from: the deck itself, or the AI. */
  @Prop({ type: String, enum: ["local", "ai"], default: "local" })
  source: "local" | "ai";

  @Prop({ type: Boolean, default: false })
  verified: boolean;

  /** Deck level tag (e.g. `N2`) for picking questions by JLPT level later. */
  @Prop({ type: String, default: "" })
  level?: string;

  // ── JLPT exam-bank fields (NP-406). All optional; legacy rows leave them
  // empty and keep their exact old behaviour. ─────────────────────────
  /** Standard 問題-type code (mondai.ts taxonomy). */
  @Prop({ type: String, enum: MONDAI_TYPES })
  mondai?: MondaiType;

  /** The paper part this question belongs to. */
  @Prop({ type: String, enum: QUESTION_SECTIONS })
  section?: QuestionSection;

  /** A shared reading passage (exam_stimuli) this question attaches to. */
  @Prop({ type: Types.ObjectId, ref: "ExamStimulus" })
  stimulus?: Types.ObjectId | null;

  /** Its position within the passage (1..n) or the cloze blank number. */
  @Prop({ type: Number })
  groupOrder?: number;

  /** The question number as PRINTED on the imported paper (e.g. 55); display only. */
  @Prop({ type: Number })
  printedNo?: number;

  /** The points the question is worth (default 1). */
  @Prop({ type: Number, default: 1 })
  points?: number;

  /** Content rights (NP-406 / Q-12). Defaults to `own` for admin-authored rows. */
  @Prop({ type: String, enum: QUESTION_RIGHTS, default: "own" })
  rights?: QuestionRights;

  /** Which imported paper it came from (e.g. {file, sitting, no}). */
  @Prop({ type: Object })
  sourceRef?: { file: string; sitting?: string; no?: string } | null;

  /** Cross-source duplicate fingerprint (sha1 of prompt + sorted options). */
  /** Listening clip (NP-410): which `exam_audio_assets` file, and which stretch of it. */
  @Prop({ type: Object })
  audio?: { assetId: string; startSec?: number; endSec?: number } | null;

  /** The picture printed with the question (聴解 options drawn as pictures, a 発話表現 scene): an `ExamImageService` id. */
  @Prop({ type: String })
  image?: string;

  @Prop({ type: String, index: { unique: true, sparse: true } })
  contentHash?: string;

  /** First learner whose session produced this question. */
  @Prop({ type: String, required: true })
  createdBy: string;

  @Prop({ type: String, required: true })
  dedupeKey: string;

  createdAt: Date;
  updatedAt: Date;
}

export type ExerciseQuestionDocument = HydratedDocument<ExerciseQuestion>;

export const ExerciseQuestionSchema = SchemaFactory.createForClass(ExerciseQuestion);
ExerciseQuestionSchema.index({ dedupeKey: 1 }, { unique: true });
// Pick a practice set by level and kind.
ExerciseQuestionSchema.index({ level: 1, kind: 1 });
ExerciseQuestionSchema.index({ deck: 1, card: 1 });
// NP-406 exam-bank lookups.
ExerciseQuestionSchema.index({ level: 1, mondai: 1, rights: 1 });
ExerciseQuestionSchema.index({ stimulus: 1, groupOrder: 1 });
