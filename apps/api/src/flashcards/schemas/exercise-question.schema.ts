import { Prop, Schema, SchemaFactory } from "@nestjs/mongoose";
import { HydratedDocument, Types } from "mongoose";

/**
 * The shape of a saved multiple-choice question. The vocabulary section of the
 * JLPT / Nattest practice is organised as six 問題 (mondai):
 *   1 Cách đọc kanji → `reading-pick`     2 Cách đọc Hiragana → `kanji-pick`
 *   3 Cấu tạo từ     → `formation-pick`   4 Đồng nghĩa        → `synonym-pick`
 *   5 Biểu hiện từ   → `context-pick`     6 Cách dùng từ      → `sentence-pick`
 * (`meaning-pick` is the plain flashcard-style quiz, outside those six.)
 */
export const EXERCISE_KINDS = [
  "kanji-pick", // reading shown → pick the kanji spelling
  "reading-pick", // kanji shown → pick the hiragana reading
  "meaning-pick", // word shown → pick the meaning
  "synonym-pick", // word shown → pick the synonym
  "sentence-pick", // word shown → pick the sentence that uses it correctly
  "formation-pick", // word with one kanji hidden → pick the missing kanji
  "context-pick", // sentence with a blank → pick the word that fits
] as const;
export type ExerciseKind = (typeof EXERCISE_KINDS)[number];

/**
 * One question generated by the exercises area, kept so it can be reused as an
 * item of the JLPT / Nattest practice later (spec: question bank).
 *
 * `dedupeKey` fingerprints (deck, card, kind, answer, sorted options): showing
 * the same question again never creates a second row, while a new set of
 * distractors for the same card is kept as a different question.
 * `verified` is true when the answer could be checked against the card itself
 * (everything except the AI-made synonym questions).
 */
@Schema({ _id: true, timestamps: true, collection: "exercise_questions" })
export class ExerciseQuestion {
  @Prop({ type: Types.ObjectId, ref: "FlashcardDeck", required: true })
  deck: Types.ObjectId;

  @Prop({ type: Types.ObjectId, ref: "Flashcard", required: true })
  card: Types.ObjectId;

  @Prop({ type: String, enum: EXERCISE_KINDS, required: true })
  kind: ExerciseKind;

  /** The question stem (a reading, a word, …). */
  @Prop({ type: String, required: true })
  prompt: string;

  /** A hint under the stem (usually the Vietnamese meaning). */
  @Prop({ type: String, default: "" })
  sub?: string;

  /** Exactly four distinct options, in the order they were shown. */
  @Prop({ type: [String], required: true })
  options: string[];

  @Prop({ type: String, required: true })
  answer: string;

  /** Shown after answering (e.g. a sentence's translation). */
  @Prop({ type: String, default: "" })
  explain?: string;

  /** Where the distractors came from: the deck itself, or the AI. */
  @Prop({ type: String, enum: ["local", "ai"], default: "local" })
  source: "local" | "ai";

  @Prop({ type: Boolean, default: false })
  verified: boolean;

  /** Deck level tag (e.g. `N2`) for picking questions by JLPT level later. */
  @Prop({ type: String, default: "" })
  level?: string;

  /** First learner whose session produced this question. */
  @Prop({ type: String, required: true })
  createdBy: string;

  @Prop({ type: String, required: true })
  dedupeKey: string;

  createdAt: Date;
  updatedAt: Date;
}

export type ExerciseQuestionDocument = HydratedDocument<ExerciseQuestion>;

export const ExerciseQuestionSchema = SchemaFactory.createForClass(ExerciseQuestion);
ExerciseQuestionSchema.index({ dedupeKey: 1 }, { unique: true });
// Pick a practice set by level and kind.
ExerciseQuestionSchema.index({ level: 1, kind: 1 });
ExerciseQuestionSchema.index({ deck: 1, card: 1 });
